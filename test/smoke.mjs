// Manual smoke check: start the stdio server from src and exercise the docs surface.
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
const transport = new StdioClientTransport({ command: process.execPath, args: ['src/cli.ts'], env: { PATH: process.env.PATH ?? '', SYSTEMROOT: process.env.SYSTEMROOT ?? '' }, stderr: 'pipe' });
let err = '';
transport.stderr?.on('data', (d) => { err += d; });
const client = new Client({ name: 'smoke', version: '0' });
await client.connect(transport);
const tools = await client.listTools();
console.log('TOOLS', tools.tools.map((t) => t.name).join(', '));
const prompts = await client.listPrompts();
console.log('PROMPTS', prompts.prompts.map((p) => p.name).join(', '));
const res = await client.listResources();
console.log('RESOURCES', res.resources.length, res.resources.slice(0, 4).map((r) => r.uri).join(' '));
const t = await client.listResourceTemplates();
console.log('TEMPLATES', t.resourceTemplates.map((r) => r.uriTemplate).join(' '));
const show = async (name, args) => { const r = await client.callTool({ name, arguments: args }); console.log('==', name, JSON.stringify(args), r.isError ? 'ERROR' : '', '\n' + r.content[0].text.slice(0, Number(process.env.CHARS ?? 600))); };
await show('learn_kits', {});
await show('learn_guide', { topic: 'safety' });
await show('learn_contract', {});
await show('learn_contract', { operation: 'POST /v1/chat' });
await show('learn_kit', { kit: '1' });
await show('learn_starter_file', { kit: 'embed', path: 'learn-route.ts' });
await show('learn_test_turn', { message: 'hi', confirm: true });
const p = await client.getPrompt({ name: 'first-tutor' });
console.log('PROMPT first-tutor starts:', JSON.stringify(p.messages[0].content.text.slice(0, 120)));
console.log('INSTRUCTIONS', client.getInstructions?.()?.slice(0, 300));
console.log('STDERR', err.trim());
await client.close();
